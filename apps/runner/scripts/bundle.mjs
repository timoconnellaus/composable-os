// Build-time bundling for the extension runtime (ADR 0025):
//
// 1. The SDK as one ES module string (`cos-sdk` inside the sandbox): defineExtension, z,
//    runExtension, … with zod inlined, since Dynamic Workers cannot resolve packages.
// 2. Every pack in the repository (packs/<id>/, stage 24), each the shipped extension as source
//    text (its .ts files, minus tests, config, and the pack's client/ and blocks/, which are
//    client code and never run in the host), so it goes through the same transpile → check →
//    sandbox path as runtime extensions. There is no static fast path. A release carries them all
//    so a client product can turn any of them on at deploy (COS_PACKS); the packs the build's
//    product lists (COS_PRODUCT's, else the default product) are PRODUCT_PACKS, what COS_PACKS
//    "*" installs, so the release product's own deployments install what they always did.
// 3. The declarations for the in-Worker type check of extension source (sdk-types.ts).
// 4. The TypeScript compiler as an ES module (typescript.js), and the type checker's Dynamic Worker
//    (checker.txt: the compiler, the declarations and src/checker/entry.ts in one module). The
//    checker runs in its own Dynamic Worker (ADR 0043), so cos-runner's main bundle does not carry
//    or parse the compiler; it ships checker.txt as a Text module.
// 5. runtime-meta.ts: hashes that go into the Dynamic Workers' stable loader ids (ADR 0043).
//
// Writes src/generated/{shipped,sdk-types,runtime-meta}.ts, sdk-bundle.txt, checker.txt and
// typescript.{js,d.ts} (gitignored). Runs before typecheck, test, dev and build (see package.json).
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import ts from "typescript";
import {
  buildSdkTypes,
  sdkBundleOptions,
} from "../../../packages/extension-check/src/sdk-artifacts.ts";
import { loadProduct } from "../../../packages/product/src/node.ts";
import { releasePacks } from "../../../packages/product/src/packs.ts";
import { DEFAULT_PRODUCT } from "../../../products/index.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(here, "..", "src", "generated");

const sdk = await build(sdkBundleOptions(join(root, "packages", "sdk", "src", "index.ts")));
const sdkSource = sdk.outputFiles[0].text;

const product = await loadProduct(process.env.COS_PRODUCT?.trim() || DEFAULT_PRODUCT);
const shipped = releasePacks(root);
for (const id of product.packs) {
  if (!shipped.some((p) => p.id === id))
    throw new Error(`product ${product.id} lists the pack ${id}, which is not in packs/`);
}

// 3. The declarations the in-Worker type checker needs (src/extensions/typecheck.ts): @composable-os/sdk's
//    .d.ts (emitted from packages/sdk/src), the zod .d.ts files they reach, and the ES2022 lib
//    files (no DOM), comments stripped, at virtual paths, plus every import's resolution between
//    them, so the Worker needs no module resolution of its own for these files. Built by the
//    code `cos ext check` uses (packages/extension-check/src/sdk-artifacts.ts).
const sdkTypes = buildSdkTypes(ts, join(root, "packages", "sdk", "src"));
const sdkTypesJson = JSON.stringify(sdkTypes);

// 4. The TypeScript compiler as an ES module for the Worker, minified. typescript.js picks Node's
//    `ts.sys` when `process` and `require` exist, which nodejs_compat provides, and that path reads
//    `__filename` at load and fails; `process.browser` set to true makes it skip `ts.sys` (the
//    checker uses its own in-memory host). Its Node-only requires are never reached.
const typescript = await build({
  entryPoints: [fileURLToPath(import.meta.resolve("typescript"))],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  minify: true,
  write: false,
  legalComments: "none",
  define: { "process.browser": "true" },
  external: ["fs", "path", "os", "crypto", "inspector", "perf_hooks", "source-map-support"],
});
const typescriptSource = typescript.outputFiles[0].text;

await mkdir(out, { recursive: true });
const banner = "// Generated by apps/runner/scripts/bundle.mjs. Do not edit.\n";
await writeFile(join(out, "typescript.js"), typescriptSource);
await writeFile(
  join(out, "typescript.d.ts"),
  `${banner}import ts from "typescript";\nexport default ts;\n`,
);
await writeFile(
  join(out, "sdk-types.ts"),
  `${banner}/** Declarations for the extension type checker: @composable-os/sdk, zod and the ES2022 libs. */\nexport const SDK_TYPES: { entry: string; files: Record<string, string>; resolutions: Record<string, Record<string, string>> } = ${sdkTypesJson};\n`,
);
// @composable-os/sdk as one ES module for the sandbox (specifier `cos-sdk`), shipped as a Text module so the
// runner never parses it as code.
await writeFile(join(out, "sdk-bundle.txt"), sdkSource);
// The packs' sources go in a Text module too (2026-11-22): as a JS literal they were parsed as
// code at every cold start and grew the main module by each pack's whole source (8 packs, 359 KiB
// of a 7,168 KiB budget); as text they are one JSON.parse, and not part of the main module.
await writeFile(join(out, "shipped.txt"), JSON.stringify(shipped));
await writeFile(
  join(out, "shipped.ts"),
  `${banner}/** The packs this release carries (every packs/<id>/), the shipped extensions, as source. */\nimport SHIPPED_TEXT from "./shipped.txt";\nexport const PRODUCT_PACKS: readonly string[] = ${JSON.stringify([...product.packs].sort())};\nexport const SHIPPED_EXTENSIONS: readonly { id: string; version: string; optional?: boolean; label?: string; description?: string; files: Record<string, string> }[] = JSON.parse(SHIPPED_TEXT);\n`,
);

// The checker's Dynamic Worker: one ES module with the compiler, the declarations and the entry.
const checker = await build({
  entryPoints: [join(here, "..", "src", "checker", "entry.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  minify: true,
  write: false,
  legalComments: "none",
  external: [
    "cloudflare:workers",
    "fs",
    "path",
    "os",
    "crypto",
    "inspector",
    "perf_hooks",
    "source-map-support",
  ],
});
const checkerSource = checker.outputFiles[0].text;
await writeFile(join(out, "checker.txt"), checkerSource);

const sha = (...parts) => {
  const hash = createHash("sha256");
  for (const part of parts) hash.update(part).update("\0");
  return hash.digest("hex");
};
/** The version of a dependency: the nearest package.json above its resolved entry. */
function pkgVersion(name) {
  let dir = dirname(fileURLToPath(import.meta.resolve(name)));
  for (;;) {
    try {
      const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      if (pkg.name === name) return pkg.version;
    } catch {}
    const up = dirname(dir);
    if (up === dir) throw new Error(`no package.json for ${name}`);
    dir = up;
  }
}
const typescriptVersion = pkgVersion("typescript");
const sucraseVersion = pkgVersion("sucrase");
// Everything that decides what a build produces and how its worker runs: the SDK bundle, the
// transpiler and its version, the build rules and the fixed entry module.
const runtimeHash = sha(
  sdkSource,
  sucraseVersion,
  readFileSync(join(root, "packages", "extension-check", "src", "build.ts"), "utf8"),
  readFileSync(join(here, "..", "src", "executor", "worker-code.ts"), "utf8"),
);
await writeFile(
  join(out, "runtime-meta.ts"),
  `${banner}/** Hashes in the Dynamic Workers' stable loader ids (ADR 0043). */
export const SDK_HASH = ${JSON.stringify(sha(sdkSource))};
/** The SDK bundle, sucrase, build.ts and the entry module: what a build and its worker depend on. */
export const RUNTIME_HASH = ${JSON.stringify(runtimeHash)};
/** The type checker's worker: the compiler, the SDK declarations and the checker entry. */
export const CHECKER_HASH = ${JSON.stringify(sha(checkerSource))};
export const TYPESCRIPT_VERSION = ${JSON.stringify(typescriptVersion)};
export const SDK_TYPES_HASH = ${JSON.stringify(sha(sdkTypesJson))};
`,
);
console.log(
  `bundled cos-sdk (${(sdkSource.length / 1024).toFixed(0)} KiB), its type declarations (${Object.keys(sdkTypes.files).length} files, ${(sdkTypesJson.length / 1024).toFixed(0)} KiB), the checker worker with typescript ${typescriptVersion} (${(checkerSource.length / 1024).toFixed(0)} KiB) and ${shipped.length} pack(s) (${product.id} installs ${product.packs.length} by default)`,
);
