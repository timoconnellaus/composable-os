// Writes src/generated/schema-version.ts: CORE_SCHEMA_VERSION, the highest number among the
// migration files in migrations/. It is derived, not hand-edited, so parallel PRs that each add a
// migration never edit the same line (CONTRIBUTING.md, Working in parallel). The file is
// gitignored. It is written on install and before this package's typecheck, test and build (see
// package.json), and by the release build through `pnpm build`.
//
// Node alone, no dependencies: `node packages/db/scripts/schema-version.mjs` from anywhere.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE = join(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = join(PACKAGE, "migrations");
const OUT = join(PACKAGE, "src", "generated", "schema-version.ts");

/** The highest number a `NNNN_name.sql` file in `dir` starts with. */
export function highestMigrationFile(dir = MIGRATIONS) {
  let highest = null;
  for (const name of readdirSync(dir)) {
    const match = /^(\d+)_.*\.sql$/.exec(name);
    if (!match) continue;
    const n = Number.parseInt(match[1], 10);
    if (highest === null || n > highest) highest = n;
  }
  if (highest === null) throw new Error(`no migrations in ${dir}`);
  return highest;
}

/** Writes the generated module when its content changed. Returns the version. */
export function writeSchemaVersion() {
  const version = highestMigrationFile();
  const text = `// Generated by packages/db/scripts/schema-version.mjs from the migration files. Do not edit.
export const CORE_SCHEMA_VERSION = ${version};
`;
  let current = null;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // Not written yet.
  }
  if (current !== text) {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, text);
  }
  return version;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeSchemaVersion();
