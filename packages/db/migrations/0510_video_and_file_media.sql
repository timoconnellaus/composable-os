-- Stage 42, Courses (ADRs 0475 and 0477): videos and downloadable files in the media library, and
-- which part of a published document each media item is in.
--
-- 1. core_media gains a kind. A `video` is held in Cloudflare Stream on the deployment's own
--    account: the row keeps Stream's id for it (`stream_uid`), its state (uploading, processing,
--    ready, failed, and Stream's reason when it failed), its duration and dimensions; nothing of
--    it is in R2, so it has no `key`. A `file` (a PDF, for downloads) is in R2 like a picture.
--    SQLite cannot change a CHECK, so the table is rebuilt with its rows, indexes and trigger.
-- 2. Deleting a row (the Trash purge) queues what it holds on core_blob_deletion in the same
--    batch: its R2 key, or `stream/<uid>` for a video, which the drain deletes from Stream.
-- 3. core_media_caption: a video's caption tracks, one per language (WebVTT, uploaded by staff or
--    generated by Stream).
-- 4. core_published_media gains `reach`: who outside the org reads the part of the field the item
--    is in (all who read the field, only holders of access to the record, or no one: a private
--    part). Existing rows are `all`, which is what media.serve has read them as until now; the
--    next publish of a record writes its exact reach.
CREATE TABLE core_media_next (
  id TEXT PRIMARY KEY NOT NULL,
  kind TEXT NOT NULL DEFAULT 'image' CHECK (kind IN ('image', 'video', 'file')),
  key TEXT UNIQUE,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
  type TEXT NOT NULL,
  bytes INTEGER NOT NULL CHECK (bytes > 0),
  width INTEGER,
  height INTEGER,
  alt TEXT CHECK (alt IS NULL OR length(alt) <= 500),
  stream_uid TEXT UNIQUE,
  state TEXT,
  state_reason TEXT CHECK (state_reason IS NULL OR length(state_reason) <= 200),
  duration REAL,
  created_at TEXT NOT NULL,
  created_by TEXT,
  updated_at TEXT NOT NULL,
  updated_by TEXT,
  deleted_at TEXT,
  deleted_by TEXT,
  sha256 TEXT,
  CHECK (
    (kind = 'image' AND type IN ('image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/avif')
      AND key IS NOT NULL AND stream_uid IS NULL AND state IS NULL)
    OR (kind = 'file' AND type IN ('application/pdf')
      AND key IS NOT NULL AND stream_uid IS NULL AND state IS NULL)
    OR (kind = 'video' AND type = 'video/stream' AND key IS NULL AND stream_uid IS NOT NULL
      AND state IN ('uploading', 'processing', 'ready', 'failed'))
  )
);

INSERT INTO core_media_next (id, kind, key, name, type, bytes, width, height, alt, created_at,
  created_by, updated_at, updated_by, deleted_at, deleted_by, sha256)
SELECT id, 'image', key, name, type, bytes, width, height, alt, created_at, created_by,
  updated_at, updated_by, deleted_at, deleted_by, sha256
FROM core_media;

DROP VIEW rec_media;
DROP TABLE core_media;
ALTER TABLE core_media_next RENAME TO core_media;

CREATE INDEX core_media_live_idx ON core_media (created_at) WHERE deleted_at IS NULL;
CREATE INDEX core_media_deleted_idx ON core_media (deleted_at) WHERE deleted_at IS NOT NULL;
CREATE INDEX core_media_sha256_idx ON core_media (sha256) WHERE deleted_at IS NULL AND sha256 IS NOT NULL;

-- The purge's delete queues what the row held, for the drain to delete after the commit.
CREATE TRIGGER core_media_object_ad AFTER DELETE ON core_media
BEGIN
  INSERT OR IGNORE INTO core_blob_deletion (key, queued_at)
  SELECT COALESCE(OLD.key, 'stream/' || OLD.stream_uid), strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
  WHERE OLD.key IS NOT NULL OR OLD.stream_uid IS NOT NULL;
END;

-- The live media items, as staff list them. Outsiders read none of it: an item reaches them only
-- through media.serve (pictures and files) or media.play (videos).
CREATE VIEW rec_media AS
  SELECT id, kind, key, name, type, bytes, width, height, alt, stream_uid, state, state_reason,
    duration, created_at, created_by, updated_at, updated_by
  FROM core_media WHERE deleted_at IS NULL;

-- A video's caption tracks: one per language. `state` is Stream's for a generated one.
CREATE TABLE core_media_caption (
  media_id TEXT NOT NULL,
  language TEXT NOT NULL CHECK (length(language) BETWEEN 2 AND 35),
  label TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 100),
  generated INTEGER NOT NULL DEFAULT 0 CHECK (generated IN (0, 1)),
  state TEXT NOT NULL CHECK (state IN ('processing', 'ready', 'failed')),
  created_at TEXT NOT NULL,
  created_by TEXT,
  PRIMARY KEY (media_id, language)
) WITHOUT ROWID;

-- A purged video takes its captions with it (Stream deletes them with the video).
CREATE TRIGGER core_media_caption_ad AFTER DELETE ON core_media
BEGIN
  DELETE FROM core_media_caption WHERE media_id = OLD.id;
END;

CREATE TABLE core_published_media_next (
  media_id TEXT NOT NULL,
  object_type TEXT NOT NULL,
  record_id TEXT NOT NULL,
  field TEXT NOT NULL,
  reach TEXT NOT NULL DEFAULT 'all' CHECK (reach IN ('all', 'holders', 'private')),
  PRIMARY KEY (media_id, object_type, record_id, field, reach)
) WITHOUT ROWID;

INSERT INTO core_published_media_next (media_id, object_type, record_id, field, reach)
SELECT media_id, object_type, record_id, field, 'all' FROM core_published_media;

DROP TABLE core_published_media;
ALTER TABLE core_published_media_next RENAME TO core_published_media;
CREATE INDEX core_published_media_record_idx ON core_published_media (object_type, record_id);
