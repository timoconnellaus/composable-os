// Writes a product's typed client from its contract (stage 23, ADR 0418). Three entry points,
// split by audience:
//
// - `customer.ts`: the operations open to customers and the public. A customer app imports only
//   this file, so its bundle names no staff operation.
// - `staff.ts`: the operations open to staff.
// - `practitioner.ts`: the operations open to practitioners (stage 43, ADR 0581), for the screens
//   of the business's web app a signed-in practitioner uses. It names no customer, public or
//   staff operation.
//
// Each holds the operation types (input, output, query or mutation), a table of specs the runtime
// needs (kind and what a mutation makes stale), and a factory over @composable-os/client.
import type { ApiContract, ContractOperation } from "@composable-os/core/http-contract";
import { schemaToTs } from "./schema-ts.ts";

export interface RenderOptions {
  /** The product's id, written in the files' header. */
  product: string;
  /** The module the runtime is imported from. Default `@composable-os/client`. */
  runtime?: string;
}

export const ENTRY_POINTS = ["customer", "staff", "practitioner"] as const;
export type EntryPoint = (typeof ENTRY_POINTS)[number];

function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]?.toUpperCase() + part.slice(1))
    .join("");
}

function doc(op: ContractOperation): string {
  const text = op.description.replace(/\*\//g, "* /").split("\n").join("\n   * ");
  return `  /**\n   * ${text}\n   */`;
}

const WHOSE: Record<EntryPoint, string> = {
  customer: "operations open to customers and the public",
  staff: "operations open to staff",
  practitioner: "operations open to practitioners",
};

/** Which operations an entry point holds. */
export function operationsFor(contract: ApiContract, entry: EntryPoint): ContractOperation[] {
  const audiences =
    entry === "customer"
      ? ["customer", "public"]
      : entry === "practitioner"
        ? ["practitioner"]
        : ["staff"];
  return contract.operations.filter((op) => op.audiences.some((a) => audiences.includes(a)));
}

export function renderEntry(
  contract: ApiContract,
  entry: EntryPoint,
  options: RenderOptions,
): string {
  const ops = operationsFor(contract, entry);
  const names = new Set(ops.map((op) => op.name));
  const runtime = options.runtime ?? "@composable-os/client";
  const factory = `create${pascal(entry)}Client`;
  const lines: string[] = [
    `// Generated by \`cos client generate\` for the ${options.product} product, API ${contract.version}: the`,
    `// ${WHOSE[entry]}. Do not edit; generate again.`,
    `import { type ClientOptions, createClient } from ${JSON.stringify(runtime)};`,
    "",
    "/** Every operation's input, output and kind. */",
    // A type, not an interface: it must fit the runtime's Record constraint.
    "export type Operations = {",
  ];
  for (const op of ops) {
    lines.push(doc(op));
    lines.push(`  ${JSON.stringify(op.name)}: {`);
    lines.push(`    kind: ${JSON.stringify(op.kind)};`);
    lines.push(`    input: ${schemaToTs(op.input)};`);
    lines.push(`    output: ${schemaToTs(op.output)};`);
    lines.push("  };");
  }
  lines.push("};", "");
  lines.push(
    "/** What the runtime needs: each operation's kind, and what a mutation makes stale. */",
  );
  lines.push("export const operations = {");
  for (const op of ops) {
    const stale = op.invalidates.filter((n) => names.has(n));
    lines.push(
      `  ${JSON.stringify(op.name)}: { kind: ${JSON.stringify(op.kind)}, invalidates: ${JSON.stringify(stale)} },`,
    );
  }
  lines.push("} as const;", "");
  lines.push(`export const API_VERSION = ${JSON.stringify(contract.version)};`, "");
  lines.push(`export function ${factory}(options: ClientOptions) {`);
  lines.push("  return createClient<Operations>(operations, options);");
  lines.push("}", "");
  lines.push(`export type ${pascal(entry)}Client = ReturnType<typeof ${factory}>;`);
  lines.push(`export type Input<N extends keyof Operations> = Operations[N]["input"];`);
  lines.push(`export type Output<N extends keyof Operations> = Operations[N]["output"];`);
  return `${lines.join("\n")}\n`;
}

/** One pack role, as the release's roles.json lists it (ADR 0436, ADR 0451). */
export interface RoleSpec {
  name: string;
  read: string[];
  operations: string[];
}

/**
 * A client for one pack role (ADR 0451): only the staff operations a holder of the role may call
 * (its tools, and record.get and record.list typed to take only the objects it reads), so a
 * customer-facing app that needs the role (a door scanner in the company's own app) never
 * carries the staff client. Written to `roles/<pack>.<role>.ts`; its factory is
 * `create<Pack><Role>Client`.
 */
export function renderRoleClient(
  staff: ApiContract,
  role: RoleSpec,
  options: RenderOptions & {
    /**
     * Grantable pack permissions whose tools `role.operations` already includes (ADR 0600): named
     * in the header, so the file says why it holds more than the role.
     */
    grants?: readonly string[];
  },
): string {
  const allowed = new Set(role.operations);
  const missing = role.operations.filter((n) => !staff.operations.some((op) => op.name === n));
  if (missing.length) {
    throw new Error(`The role ${role.name} names ${missing.join(", ")}, not in the staff contract`);
  }
  const operations = staff.operations
    .filter((op) => allowed.has(op.name))
    .map((op) => {
      if (op.name !== "record.get" && op.name !== "record.list") return op;
      // The generic reads take only the role's own objects: the host refuses any other.
      const props = (op.input.properties ?? {}) as Record<string, unknown>;
      return {
        ...op,
        input: {
          ...op.input,
          properties: { ...props, object: { type: "string", enum: [...role.read].sort() } },
        },
      };
    });
  const text = renderEntry({ version: staff.version, operations }, "staff", options);
  const factory = `create${pascal(role.name)}Client`;
  const grants = options.grants?.length
    ? `\n// With the grants ${options.grants.join(", ")}: the tools a human admin's grant of each opens (ADR 0600).`
    : "";
  return text
    .replace(
      /^\/\/ Generated by .*\n\/\/ .*\n/,
      `// Generated by \`cos client generate\` for the ${options.product} product, API ${staff.version}: the\n// operations the ${role.name} role may call, and no other staff operation. Do not edit; generate again.${grants}\n`,
    )
    .replaceAll("createStaffClient", factory)
    .replaceAll("StaffClient", `${pascal(role.name)}Client`);
}

/**
 * The owner's client (stage 60, ADR 0872): only the staff operations the owner's Today needs, as
 * the release lists them (`roles.json`'s `owner`). Written to `roles/owner.ts`; its factory is
 * `createOwnerClient`. Not a pack role's: any staff account may sign in with it, and the host
 * decides every call, so `record.get` and `record.list` are never in it.
 */
export function renderOwnerClient(
  staff: ApiContract,
  owner: { operations: readonly string[] },
  options: RenderOptions,
): string {
  const allowed = new Set(owner.operations);
  const missing = owner.operations.filter((n) => !staff.operations.some((op) => op.name === n));
  if (missing.length) {
    throw new Error(`The owner's client names ${missing.join(", ")}, not in the staff contract`);
  }
  const operations = staff.operations.filter((op) => allowed.has(op.name));
  const text = renderEntry({ version: staff.version, operations }, "staff", options);
  return text
    .replace(
      /^\/\/ Generated by .*\n\/\/ .*\n/,
      `// Generated by \`cos client generate\` for the ${options.product} product, API ${staff.version}: the\n// operations the owner's client may call (Today, the approvals, the notice inbox), and no other\n// staff operation. Any staff account may sign in with it: the host decides every call. Do not\n// edit; generate again.\n`,
    )
    .replaceAll("createStaffClient", "createOwnerClient")
    .replaceAll("StaffClient", "OwnerClient");
}

/** Every entry point, by file name. */
export function renderClient(
  contract: ApiContract,
  options: RenderOptions,
): Record<string, string> {
  return Object.fromEntries(
    ENTRY_POINTS.map((entry) => [`${entry}.ts`, renderEntry(contract, entry, options)]),
  );
}
